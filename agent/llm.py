import os
import re
from abc import ABC, abstractmethod
from typing import List, Dict, Optional


class BaseLLM(ABC):
    """Abstract interface for LLM backends."""

    @abstractmethod
    def generate(self, prompt: str, system_prompt: Optional[str] = None) -> str:
        """Generate response from prompt."""
        pass


class MockLLM(BaseLLM):
    """
    Intelligent simulated LLM for testing and zero-dependency offline demos.
    Follows the ReAct prompting schema (Thought -> Action -> Action Input -> Final Answer).
    """

    def generate(self, prompt: str, system_prompt: Optional[str] = None) -> str:
        prompt_lower = prompt.lower()
        sys_lower = (system_prompt or "").lower()

        # Check if we already have observations from previous actions in the prompt
        if "observation:" in prompt_lower:
            last_obs_match = re.findall(r"Observation:\s*(.*?)(?=\nThought:|\Z)", prompt, re.DOTALL | re.IGNORECASE)
            last_obs = last_obs_match[-1].strip() if last_obs_match else ""
            return (
                f"Thought: I have obtained the necessary observation to fulfill the user's request.\n"
                f"Final Answer: {last_obs}"
            )

        # Check for custom weather tool if available
        if "weather" in prompt_lower and "weather" in sys_lower:
            city_match = re.search(r"weather\s+(?:in|for|at)?\s*([a-zA-Z\s]+)", prompt, re.IGNORECASE)
            city = city_match.group(1).strip().rstrip("?").strip() if city_match else "Hanoi"
            return (
                f"Thought: The user is asking for the weather forecast. I will call the weather tool.\n"
                f"Action: get_weather\n"
                f"Action Input: {city}"
            )

        # 1. Math calculation request
        math_match = re.search(r"calculate\s+(.+)$", prompt, re.IGNORECASE)
        if not math_match:
            # Must contain at least one digit to be a math question
            possible_math = re.search(r"(?:what is|how much is)\s+([^?\n]+)", prompt, re.IGNORECASE)
            if possible_math and re.search(r"\d", possible_math.group(1)):
                math_match = possible_math
        if math_match:
            expr = math_match.group(1).strip().rstrip("?").strip()
            return (
                f"Thought: The user is asking to calculate a mathematical expression. I should use the calculator tool.\n"
                f"Action: calculator\n"
                f"Action Input: {expr}"
            )

        # 2. Time or system info request
        if any(w in prompt_lower for w in ["time", "date", "os", "system info", "what day"]):
            return (
                "Thought: The user is asking for system information or current time. I will query the get_system_info tool.\n"
                "Action: get_system_info\n"
                "Action Input: current_time"
            )

        # 3. File write request
        if "write" in prompt_lower and ("file" in prompt_lower or ".txt" in prompt_lower or ".md" in prompt_lower):
            # Try extracting filepath and text
            file_match = re.search(r"(?:to|in)\s+([\w\.\/\-\\]+\.\w+)", prompt, re.IGNORECASE)
            filepath = file_match.group(1) if file_match else "output.txt"
            content = "This file was autonomously generated by SmartAgent!"
            return (
                f"Thought: The user wants to write content to a file. I will use the write_file tool.\n"
                f"Action: write_file\n"
                f"Action Input: {filepath}:::{content}"
            )

        # 4. Search or definition request
        if any(w in prompt_lower for w in ["what is", "who is", "explain", "search", "tell me about"]):
            query = prompt.split("Question:")[-1].strip().split("\n")[0]
            query = re.sub(r"^(what is|who is|explain|search for|tell me about)\s+", "", query, flags=re.IGNORECASE).rstrip("?")
            return (
                f"Thought: The user is seeking knowledge or definitions. I will use the web_search tool.\n"
                f"Action: web_search\n"
                f"Action Input: {query}"
            )

        # General response
        return (
            "Thought: I can directly answer this query without invoking external tools.\n"
            "Final Answer: Hello! I am SmartAgent, an autonomous AI assistant powered by the ReAct reasoning loop. How can I help you today?"
        )


class OpenAILLM(BaseLLM):
    """OpenAI API integration (optional dependency)."""

    def __init__(self, model: str = "gpt-4o-mini", api_key: Optional[str] = None):
        try:
            from openai import OpenAI
            self.client = OpenAI(api_key=api_key or os.getenv("OPENAI_API_KEY"))
            self.model = model
        except ImportError:
            raise ImportError("Please install openai: pip install openai")

    def generate(self, prompt: str, system_prompt: Optional[str] = None) -> str:
        messages = []
        if system_prompt:
            messages.append({"role": "system", "content": system_prompt})
        messages.append({"role": "user", "content": prompt})
        resp = self.client.chat.completions.create(
            model=self.model,
            messages=messages,
            temperature=0.2,
        )
        return resp.choices[0].message.content or ""
